"""Next-day PV yield forecasting with time-ordered machine learning."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingRegressor

from .physics import clear_sky_index, physics_yield

try:
    from lightgbm import LGBMRegressor
except (ImportError, OSError):  # pragma: no cover - depends on native runtime support
    LGBMRegressor = None

FEATURE_COLUMNS = [
    "ghi",
    "ghi_clear",
    "clear_sky_index",
    "t_amb",
    "t_max",
    "t_min",
    "rh",
    "wind",
    "precip",
    "day_of_year_sin",
    "day_of_year_cos",
    "ghi_lag_1",
    "ghi_lag_2",
    "ghi_lag_3",
    "ghi_lag_7",
    "ghi_rolling_7",
]


@dataclass
class TimeSplit:
    train: pd.DataFrame
    validation: pd.DataFrame
    test: pd.DataFrame


def build_features(df: pd.DataFrame) -> pd.DataFrame:
    """Build weather-history features without using future observations."""
    required = {"ghi", "ghi_clear", "t_amb", "t_max", "t_min", "rh", "wind", "precip"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Weather data is missing feature columns: {sorted(missing)}")
    features = df.copy().sort_index()
    day_of_year = features.index.dayofyear.to_numpy(dtype=float)
    features["clear_sky_index"] = clear_sky_index(features)
    features["day_of_year_sin"] = np.sin(2 * np.pi * day_of_year / 365.25)
    features["day_of_year_cos"] = np.cos(2 * np.pi * day_of_year / 365.25)
    for lag in (1, 2, 3, 7):
        features[f"ghi_lag_{lag}"] = features["ghi"].shift(lag)
    features["ghi_rolling_7"] = features["ghi"].rolling(7, min_periods=7).mean()
    return features[FEATURE_COLUMNS].dropna()


def build_supervised_frame(
    df: pd.DataFrame,
    lat: float,
    system_kw: float = 5.0,
) -> tuple[pd.DataFrame, pd.Series]:
    """Create features for day t and proxy target physics yield on day t+1.

    The target is not metered production. It is a proxy label generated by the
    physics model from the true next-day weather, so the ML task is a
    day-ahead weather-history forecast.
    """
    features = build_features(df)
    physics = physics_yield(df, lat=lat, system_kw=system_kw)
    target = physics.shift(-1).rename("target_next_day")
    aligned = features.join(target).dropna()
    return aligned[FEATURE_COLUMNS], aligned["target_next_day"]


def split_time_ordered(
    features: pd.DataFrame,
    target: pd.Series,
    train_fraction: float = 0.70,
    validation_fraction: float = 0.15,
) -> TimeSplit:
    """Split chronologically into train, validation, and test windows."""
    if len(features) != len(target):
        raise ValueError("features and target must have the same length")
    if len(features) < 10:
        raise ValueError("at least 10 rows are required for a time split")
    frame = features.copy()
    frame["target"] = target
    train_end = max(1, int(len(frame) * train_fraction))
    validation_end = max(train_end + 1, int(len(frame) * (train_fraction + validation_fraction)))
    validation_end = min(validation_end, len(frame) - 1)
    return TimeSplit(
        train=frame.iloc[:train_end],
        validation=frame.iloc[train_end:validation_end],
        test=frame.iloc[validation_end:],
    )


def _make_model(random_state: int = 42) -> Any:
    if LGBMRegressor is not None:
        return LGBMRegressor(
            n_estimators=250,
            learning_rate=0.04,
            num_leaves=24,
            subsample=0.85,
            colsample_bytree=0.9,
            random_state=random_state,
            verbosity=-1,
        )
    return GradientBoostingRegressor(
        n_estimators=180,
        learning_rate=0.04,
        max_depth=3,
        random_state=random_state,
    )


def train_forecaster(
    df: pd.DataFrame,
    lat: float,
    system_kw: float = 5.0,
    city: str | None = None,
    model_dir: str | Path | None = None,
    random_state: int = 42,
) -> dict[str, Any]:
    """Train a time-based next-day forecaster and optionally persist it."""
    features, target = build_supervised_frame(df, lat=lat, system_kw=system_kw)
    split = split_time_ordered(features, target)
    model = _make_model(random_state=random_state)
    model.fit(split.train[FEATURE_COLUMNS], split.train["target"])
    result = {
        "model": model,
        "features": features,
        "target": target,
        "split": split,
        "model_name": "LightGBM" if LGBMRegressor is not None else "GradientBoosting",
    }
    if city is not None:
        output_dir = Path(model_dir) if model_dir else Path(__file__).resolve().parents[2] / "data" / "models"
        output_dir.mkdir(parents=True, exist_ok=True)
        joblib.dump(result, output_dir / f"{city}.pkl")
    return result


def persistence_predictions(df: pd.DataFrame, lat: float, system_kw: float = 5.0) -> pd.Series:
    """Predict tomorrow's yield as today's physics yield."""
    return physics_yield(df, lat=lat, system_kw=system_kw).rename("persistence")