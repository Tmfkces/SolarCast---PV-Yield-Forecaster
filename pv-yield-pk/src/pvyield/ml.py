"""Next-day PV yield forecasting with time-ordered machine learning."""

from __future__ import annotations

import inspect
import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import GradientBoostingRegressor

from .physics import clear_sky_index, physics_yield

logger = logging.getLogger(__name__)

try:
    import lightgbm as lgb
    from lightgbm import LGBMRegressor
except (ImportError, OSError):  # pragma: no cover - depends on native runtime support
    lgb = None
    LGBMRegressor = None

MODEL_FORMAT_VERSION = 2
WEATHER_COLUMNS = ["ghi", "ghi_clear", "t_amb", "t_max", "t_min", "rh", "wind", "precip"]
FEATURE_COLUMNS = [
    "ghi",
    "ghi_clear",
    "clear_sky_index",
    "t_amb",
    "t_max",
    "t_min",
    "rh",
    "wind",
    "precip",
    "day_of_year_sin",
    "day_of_year_cos",
    "ghi_lag_1",
    "ghi_lag_2",
    "ghi_lag_3",
    "ghi_lag_7",
    "ghi_rolling_7",
]
MAX_BOOSTING_ROUNDS = 1_000
EARLY_STOPPING_ROUNDS = 50


@dataclass
class TimeSplit:
    train: pd.DataFrame
    validation: pd.DataFrame
    test: pd.DataFrame


@dataclass
class TrainedForecaster:
    """A fitted day-ahead model plus everything needed to evaluate it."""

    model: Any
    model_name: str
    features: pd.DataFrame
    target: pd.Series
    split: TimeSplit
    best_iteration: int
    validation_rmse: float
    physics_kwargs: dict[str, Any] = field(default_factory=dict)

    # Dict-style access keeps notebooks written against v1 (`trained["model"]`) working.
    def __getitem__(self, key: str) -> Any:
        return getattr(self, key)

    def predict(self, features: pd.DataFrame) -> pd.Series:
        """Predict next-day yield (kWh) for each feature row, clipped at zero."""
        values = self.model.predict(features[FEATURE_COLUMNS])
        return pd.Series(values, index=features.index, name=self.model_name).clip(lower=0)


def to_daily_frequency(df: pd.DataFrame) -> pd.DataFrame:
    """Re-index to a complete daily calendar so that shifts move by days, not rows."""
    if not isinstance(df.index, pd.DatetimeIndex):
        raise TypeError("weather data must have a DatetimeIndex")
    ordered = df[~df.index.duplicated(keep="last")].sort_index()
    if ordered.empty:
        return ordered
    return ordered.asfreq("D")


def build_features(df: pd.DataFrame) -> pd.DataFrame:
    """Build weather-history features for day ``t`` without future observations.

    Lags and the rolling mean are computed on a complete daily calendar, so a
    removed gap produces missing features (and the row is dropped) instead of
    silently pairing a day with an observation from weeks earlier.
    """
    missing = set(WEATHER_COLUMNS) - set(df.columns)
    if missing:
        raise ValueError(f"Weather data is missing feature columns: {sorted(missing)}")
    features = to_daily_frequency(df[WEATHER_COLUMNS]).copy()
    day_of_year = features.index.day_of_year.to_numpy(dtype=float)
    features["clear_sky_index"] = clear_sky_index(features).where(features["ghi"].notna())
    features["day_of_year_sin"] = np.sin(2 * np.pi * day_of_year / 365.25)
    features["day_of_year_cos"] = np.cos(2 * np.pi * day_of_year / 365.25)
    for lag in (1, 2, 3, 7):
        features[f"ghi_lag_{lag}"] = features["ghi"].shift(lag)
    features["ghi_rolling_7"] = features["ghi"].rolling(7, min_periods=7).mean()
    return features[FEATURE_COLUMNS].dropna()


def build_supervised_frame(
    df: pd.DataFrame,
    lat: float,
    system_kw: float = 5.0,
    **physics_kwargs: Any,
) -> tuple[pd.DataFrame, pd.Series]:
    """Create features for day ``t`` and the proxy target: physics yield on ``t + 1``.

    The target is not metered production. It is a proxy label generated by the
    physics model from the true next-day weather, so the ML task is a
    day-ahead weather-history forecast. The shift is by calendar day.
    """
    daily = to_daily_frequency(df)
    features = build_features(daily)
    physics = physics_yield(daily, lat=lat, system_kw=system_kw, **physics_kwargs)
    target = physics.shift(-1, freq="D").rename("target_next_day")
    aligned = features.join(target, how="inner").dropna()
    return aligned[FEATURE_COLUMNS], aligned["target_next_day"]


def split_time_ordered(
    features: pd.DataFrame,
    target: pd.Series,
    train_fraction: float = 0.70,
    validation_fraction: float = 0.15,
) -> TimeSplit:
    """Split chronologically into train, validation, and test windows."""
    if len(features) != len(target):
        raise ValueError("features and target must have the same length")
    if len(features) < 10:
        raise ValueError("at least 10 rows are required for a time split")
    if not (0 < train_fraction < 1 and 0 < validation_fraction < 1 and train_fraction + validation_fraction < 1):
        raise ValueError("fractions must be positive and leave room for a test window")
    frame = features.sort_index().copy()
    frame["target"] = target.reindex(frame.index)
    train_end = max(1, int(len(frame) * train_fraction))
    validation_end = max(train_end + 1, int(len(frame) * (train_fraction + validation_fraction)))
    validation_end = min(validation_end, len(frame) - 1)
    return TimeSplit(
        train=frame.iloc[:train_end],
        validation=frame.iloc[train_end:validation_end],
        test=frame.iloc[validation_end:],
    )


def _make_model(n_estimators: int, random_state: int = 42) -> Any:
    if LGBMRegressor is not None:
        return LGBMRegressor(
            n_estimators=n_estimators,
            learning_rate=0.04,
            num_leaves=24,
            min_child_samples=20,
            subsample=0.85,
            subsample_freq=1,
            colsample_bytree=0.9,
            random_state=random_state,
            verbosity=-1,
        )
    return GradientBoostingRegressor(
        n_estimators=n_estimators,
        learning_rate=0.04,
        max_depth=3,
        subsample=0.85,
        random_state=random_state,
    )


def model_family() -> str:
    """Name of the estimator that will be used in this environment."""
    return "LightGBM" if LGBMRegressor is not None else "GradientBoosting"


def _select_iterations(split: TimeSplit, random_state: int) -> tuple[int, float]:
    """Pick the number of boosting rounds on the validation window only."""
    x_train, y_train = split.train[FEATURE_COLUMNS], split.train["target"]
    x_val, y_val = split.validation[FEATURE_COLUMNS], split.validation["target"]
    model = _make_model(MAX_BOOSTING_ROUNDS, random_state)
    if LGBMRegressor is not None:
        # LightGBM >= 4.6 prefers eval_X/eval_y; older releases only accept eval_set.
        if "eval_X" in inspect.signature(model.fit).parameters:
            eval_kwargs: dict[str, Any] = {"eval_X": (x_val,), "eval_y": (y_val,)}
        else:  # pragma: no cover - depends on installed LightGBM version
            eval_kwargs = {"eval_set": [(x_val, y_val)]}
        model.fit(
            x_train,
            y_train,
            eval_metric="rmse",
            callbacks=[lgb.early_stopping(EARLY_STOPPING_ROUNDS, verbose=False)],
            **eval_kwargs,
        )
        best = int(model.best_iteration_ or MAX_BOOSTING_ROUNDS)
        rmse = float(np.sqrt(np.mean((model.predict(x_val, num_iteration=best) - y_val) ** 2)))
        return best, rmse
    model.fit(x_train, y_train)
    errors = [float(np.sqrt(np.mean((pred - y_val.to_numpy()) ** 2))) for pred in model.staged_predict(x_val)]
    best_index = int(np.argmin(errors))
    return best_index + 1, errors[best_index]


def train_forecaster(
    df: pd.DataFrame,
    lat: float,
    system_kw: float = 5.0,
    random_state: int = 42,
    **physics_kwargs: Any,
) -> TrainedForecaster:
    """Train a time-ordered next-day forecaster.

    1. Split chronologically into 70 % train / 15 % validation / 15 % test.
    2. Choose the number of boosting rounds by validation RMSE (early stopping).
    3. Refit on train + validation with that number of rounds.
    4. Leave the test window untouched for :func:`pvyield.evaluate.evaluate_forecaster`.

    Extra keyword arguments (``tilt``, ``azimuth``, ``pr``, ``soiling`` …) are
    passed to :func:`pvyield.physics.physics_yield` when building the target.
    Training never writes to disk; use :func:`save_forecaster` explicitly.
    """
    features, target = build_supervised_frame(df, lat=lat, system_kw=system_kw, **physics_kwargs)
    split = split_time_ordered(features, target)
    best_iteration, validation_rmse = _select_iterations(split, random_state)
    fit_frame = pd.concat([split.train, split.validation])
    model = _make_model(best_iteration, random_state)
    model.fit(fit_frame[FEATURE_COLUMNS], fit_frame["target"])
    logger.info("Trained %s with %d rounds (validation RMSE %.3f)", model_family(), best_iteration, validation_rmse)
    return TrainedForecaster(
        model=model,
        model_name=model_family(),
        features=features,
        target=target,
        split=split,
        best_iteration=best_iteration,
        validation_rmse=validation_rmse,
        physics_kwargs={"lat": lat, "system_kw": system_kw, **physics_kwargs},
    )


def save_forecaster(trained: TrainedForecaster, path: str | Path, city: str | None = None) -> Path:
    """Persist only the fitted model and its metadata (not the training data)."""
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    bundle = {
        "format_version": MODEL_FORMAT_VERSION,
        "model": trained.model,
        "model_name": trained.model_name,
        "feature_columns": list(FEATURE_COLUMNS),
        "best_iteration": trained.best_iteration,
        "validation_rmse": trained.validation_rmse,
        "physics_kwargs": trained.physics_kwargs,
        "city": city,
        "train_period": [str(trained.split.train.index.min().date()), str(trained.split.validation.index.max().date())],
        "sklearn_version": sklearn.__version__,
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    joblib.dump(bundle, output)
    return output


def load_forecaster(path: str | Path) -> dict[str, Any]:
    """Load a bundle written by :func:`save_forecaster`.

    Joblib files are pickles: only load files you created yourself.
    """
    bundle = joblib.load(Path(path))
    if not isinstance(bundle, dict) or bundle.get("format_version") != MODEL_FORMAT_VERSION:
        raise ValueError("Unsupported model file; retrain and save it with this version of pvyield")
    if bundle.get("feature_columns") != FEATURE_COLUMNS:
        raise ValueError("Model was trained with a different feature set")
    return bundle


def persistence_predictions(df: pd.DataFrame, lat: float, system_kw: float = 5.0, **physics_kwargs: Any) -> pd.Series:
    """Predict tomorrow's yield as today's physics yield (indexed by today)."""
    daily = to_daily_frequency(df)
    return physics_yield(daily, lat=lat, system_kw=system_kw, **physics_kwargs).rename("persistence")


def climatology_predictions(split: TimeSplit, index: pd.Index) -> pd.Series:
    """Predict tomorrow's yield as the training-period mean for tomorrow's calendar month."""
    history = pd.concat([split.train, split.validation])["target"]
    target_months = (history.index + pd.Timedelta(days=1)).month
    monthly_mean = history.groupby(target_months).mean()
    months = (pd.DatetimeIndex(index) + pd.Timedelta(days=1)).month
    values = monthly_mean.reindex(months).fillna(history.mean()).to_numpy()
    return pd.Series(values, index=index, name="climatology")
